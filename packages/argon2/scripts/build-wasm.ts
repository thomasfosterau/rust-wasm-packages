/**
 * @copyright Thomas Foster
 *
 * Compiles `src/lib.rs` to `wasm32-unknown-unknown` and emits the bytes as a
 * base64 string literal in `src/wasm.generated.ts`.
 *
 * The base64 embed is deliberate, and it is the whole reason this package can
 * be consumed identically by every build path this repo has. The alternative —
 * importing the `.wasm` as an asset — needs a bundler-specific suffix
 * (`?url` / `?inline` for Vite, `?module` / `?init` for the Cloudflare rolldown
 * plugin), and this repo runs *both*: Vitest's Vite module runner for unit
 * tests and `alchemy`'s rolldown bundle for the deployed Worker. Depending on
 * asset resolution is what broke the previous `@node-rs/argon2` integration on
 * trunk twice (#1006 → #1007). A string constant is plain JS — it has no
 * resolution behaviour to get wrong.
 *
 * The generated file is NOT committed: it is gitignored and rebuilt from the
 * Rust source on every install, so the artifact can never drift from `lib.rs`.
 *
 * @module scripts/build-wasm
 */

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = "wasm32-unknown-unknown";
const artifact = join(pkgRoot, "target", target, "release", "thomasfosterau_argon2.wasm");
const out = join(pkgRoot, "src", "wasm.generated.ts");

execFileSync("cargo", ["build", "--release", "--target", target], {
  cwd: pkgRoot,
  stdio: "inherit",
});

const bytes = readFileSync(artifact);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// @generated by scripts/build-wasm.ts from src/lib.rs — do not edit, do not commit.
/* eslint-disable */
/** argon2id compiled to \`${target}\` (${bytes.length} bytes), base64-encoded. */
export const WASM_BASE64 =
  "${bytes.toString("base64")}";
`,
);

console.log(`build-wasm: ${bytes.length} bytes -> src/wasm.generated.ts`);
